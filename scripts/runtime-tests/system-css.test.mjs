import test from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { normalizeDecisions } from "../../engine/.claude/skills/styleseed/workflows/ss-resolve/scripts/runtime-contract.mjs";
import { renderRulesSection } from "../../engine/.claude/skills/styleseed/workflows/ss-resolve/scripts/rules-in-scope.mjs";

// WO-20 Part B: a project without a registry gets `.styleseed/system.css` on every resolve. The expected texts below
// are written from the work order, not produced by the code under test.
const repoRoot = resolve(fileURLToPath(new URL("../../", import.meta.url)));
const resolver = resolve(repoRoot, "engine/.claude/skills/styleseed/workflows/ss-resolve/scripts/resolve-context.mjs");
const catalog = JSON.parse(readFileSync(resolve(repoRoot, "engine/.claude/skills/styleseed/workflows/ss-resolve/references/catalog.json"), "utf8"));

const HEAD = "/* Generated by ss-resolve from .styleseed/decisions.json and rewritten on every resolve; do not edit. A recorded corner is set on every recipe root of the document, because a project without a registry has one look. */\n";
const SELECTOR = ":root:root, [data-styleseed-recipe][data-styleseed-recipe] {\n";
const FILE = {
  none: HEAD,
  control: `${HEAD}${SELECTOR}  --ss-control-radius: 5px; /* D-002 */\n}\n`,
  field: `${HEAD}${SELECTOR}  --ss-field-radius: 9px; /* D-003 */\n}\n`,
  both: `${HEAD}${SELECTOR}  --ss-control-radius: 5px; /* D-002 */\n  --ss-field-radius: 9px; /* D-003 */\n}\n`,
};
const IMPORT = "Import the file once in the global stylesheet, outside every `@layer`.";
const PARAGRAPH = {
  none: `\`.styleseed/system.css\` draws nothing yet. ${IMPORT}`,
  control: `\`.styleseed/system.css\` draws the recorded control corner (D-002). It replaces the brand recipe's control corner; the rest of the recipe's geometry stands. ${IMPORT}`,
  field: `\`.styleseed/system.css\` draws the recorded field corner (D-003). It replaces the skin's field corner; the recipe's geometry stands. ${IMPORT}`,
  both: `\`.styleseed/system.css\` draws the recorded control corner (D-002) and field corner (D-003). They replace the brand recipe's control corner and the skin's field corner; the rest of the recipe's geometry stands. ${IMPORT}`,
};

const LOCK = `# StyleSeed — Design Lock
- App domain: saas
- Surface adapter: product-ui
- Page type: settings
- Output grammar: operations-console
- Brand recipe: enterprise-workbench
`;
const entry = (id, axis, values, statement) => ({ id, kind: "decision", ...(axis ? { axis, values } : {}), statement, approvedBy: "reviewer-a", date: "2026-11-26" });
const PROSE = entry("D-001", null, null, "Tables use hairline rows.");
const CONTROL = entry("D-002", "controlRadius", [5], "Buttons and the other controls that share their corner use a 5px corner.");
const FIELD = entry("D-003", "fieldRadius", [9], "Inputs, selects, and textareas use a 9px corner.");
const LEDGERS = { none: [PROSE], control: [PROSE, CONTROL], field: [PROSE, FIELD], both: [PROSE, CONTROL, FIELD] };

const lockProject = () => { const root = mkdtempSync(join(tmpdir(), "ss-system-css-")); writeFileSync(join(root, "STYLESEED.md"), LOCK); return root; };
const writeLedger = (root, entries) => { mkdirSync(join(root, ".styleseed"), { recursive: true }); writeFileSync(join(root, ".styleseed/decisions.json"), `${JSON.stringify(entries, null, 2)}\n`); };
const lockResolve = (root, args = []) => spawnSync(process.execPath, [resolver, "--project-root", root, "--from-lock", "STYLESEED.md", "--agent", "claude", ...args], { encoding: "utf8" });
const read = (root, path) => readFileSync(join(root, path), "utf8");
const kinds = (root, path) => JSON.parse(read(root, path)).outputs.map((output) => output.kind);
// The end of "## Project decisions": the last entry line, a blank line, then whatever follows up to "## Invariants".
const tail = (bundle) => bundle.slice(bundle.indexOf("## Project decisions"), bundle.indexOf("## Invariants"));

test("a lock project gets .styleseed/system.css in four states, and the bundle says what it draws", () => {
  const root = lockProject();
  try {
    const bare = lockResolve(root);
    assert.equal(bare.status, 0, bare.stderr);
    assert.equal(read(root, ".styleseed/system.css"), FILE.none, "no ledger: the comment line alone");
    assert.deepEqual(kinds(root, ".styleseed/manifest.json"), ["bundle", "palette-json", "palette-css", "system-css"]);
    const bareBundle = read(root, ".styleseed/effective-rules.md");
    assert.ok(!bareBundle.includes("system.css") && !bareBundle.includes("## Project decisions"), "no ledger: the bundle does not name the file");
    // The resolver prints a native path, as its other "wrote …" lines do: `\` on Windows, `/` elsewhere.
    assert.match(bare.stdout.trim().split("\n").at(-1), /^wrote .*[\\/]\.styleseed[\\/]system\.css \(draws nothing yet\); import it once in the global stylesheet, outside every @layer$/u, "the final line names the file");

    writeLedger(root, []);
    assert.equal(lockResolve(root).status, 0);
    assert.equal(read(root, ".styleseed/effective-rules.md"), bareBundle, "an empty ledger: byte-identical to no ledger");
    assert.equal(read(root, ".styleseed/system.css"), FILE.none);

    for (const state of ["none", "control", "field", "both"]) {
      writeLedger(root, LEDGERS[state]);
      const run = lockResolve(root);
      assert.equal(run.status, 0, `${state}: ${run.stderr}`);
      assert.equal(read(root, ".styleseed/system.css"), FILE[state], `${state}: the file's exact bytes`);
      const bundle = read(root, ".styleseed/effective-rules.md");
      const last = LEDGERS[state].at(-1);
      assert.ok(tail(bundle).endsWith(`): ${last.statement}\n\n${PARAGRAPH[state]}\n\n`), `${state}: the paragraph follows the entries\n${tail(bundle)}`);
      assert.ok(!tail(bundle).split("\n").some((line) => line.startsWith("- **") && line.includes("system.css")), `${state}: not a list item`);
      assert.equal(bundle.split("system.css").length - 1, 1, `${state}: the bundle names the file once`);
      assert.equal(bundle.replace(/## Project decisions\n[\s\S]*?\n\n## Invariants/u, "## Invariants"), bareBundle, `${state}: only the section is added`);
      assert.equal(lockResolve(root, ["--check"]).status, 0, `${state}: --check passes after the resolve`);
    }
    // Never removed: the corners go, the file stays with its comment line.
    writeLedger(root, LEDGERS.none);
    assert.equal(lockResolve(root).status, 0);
    assert.equal(read(root, ".styleseed/system.css"), FILE.none, "the corners removed: the file stays");
  } finally { rmSync(root, { recursive: true, force: true }); }
});

test("--check exits 2 when the ledger gained a corner without a resolve, and when the file was edited", () => {
  const root = lockProject();
  try {
    writeLedger(root, LEDGERS.none);
    assert.equal(lockResolve(root).status, 0);
    writeLedger(root, LEDGERS.both);
    const changed = lockResolve(root, ["--check"]);
    assert.equal(changed.status, 2, "a ledger that gained a corner and was not resolved again");
    assert.match(changed.stderr, /StyleSeed context drift/u);

    assert.equal(lockResolve(root).status, 0);
    assert.equal(lockResolve(root, ["--check"]).status, 0);
    writeFileSync(join(root, ".styleseed/system.css"), FILE.both.replace("5px", "6px"));
    const edited = lockResolve(root, ["--check"]);
    assert.equal(edited.status, 2, "an edited file");
    assert.match(edited.stderr, /StyleSeed context drift: output mismatch for \.styleseed\/system\.css \(expected \d+ bytes sha256:[0-9a-f]{64}, found \d+ bytes sha256:[0-9a-f]{64}\)\./u);

    // A manifest from before this version lists three outputs: the count no longer matches.
    assert.equal(lockResolve(root).status, 0);
    const manifestPath = join(root, ".styleseed/manifest.json");
    const manifest = JSON.parse(read(root, ".styleseed/manifest.json"));
    writeFileSync(manifestPath, `${JSON.stringify({ ...manifest, outputs: manifest.outputs.filter((output) => output.kind !== "system-css") }, null, 2)}\n`);
    const older = lockResolve(root, ["--check"]);
    assert.equal(older.status, 2);
    assert.match(older.stderr, /manifest outputs count mismatch: expected 4, found 3/u);
  } finally { rmSync(root, { recursive: true, force: true }); }
});

// A registry project with one artifact, its ledger in project.json.
function writeRegistry(root, decisions) {
  mkdirSync(join(root, ".styleseed/artifacts"), { recursive: true });
  mkdirSync(join(root, "src"), { recursive: true });
  writeFileSync(join(root, ".styleseed/project.json"), `${JSON.stringify({
    schemaVersion: 1, projectId: "system-css-registry",
    defaults: { agent: "codex", domain: "saas", adapter: "product-ui", recipe: "enterprise-workbench", palette: "cobalt-instrument", profile: "none", fallback: "operations-console" },
    brand: { keyColor: "#0F766E", paletteCharacter: "balanced", paletteMode: "light", paletteHarmony: "auto", surfaceTemperature: "cool", fontFamilies: ["Inter"], radius: "soft", elevation: "restrained-shadow", density: "comfortable", motion: { seed: "snap", intensity: "restrained" }, imageryRole: "data-first" },
    ...(decisions ? { decisions } : {}),
  }, null, 2)}\n`);
  writeFileSync(join(root, ".styleseed/artifacts/index.json"), `${JSON.stringify({ schemaVersion: 1, artifacts: [{ id: "app-settings", config: "app-settings.json" }] }, null, 2)}\n`);
  writeFileSync(join(root, ".styleseed/artifacts/app-settings.json"), `${JSON.stringify({
    schemaVersion: 1, id: "app-settings", target: { kind: "route", locator: "/settings" },
    selection: { grammar: "operations-console", adapter: null, domain: null, page: "settings", recipe: null, palette: null, profile: null, fallback: null },
    decisions: { primaryDecision: "Which setting needs a change?", primaryAction: "Save settings", signatureMove: "Keep the form stable." },
    implementation: { sourceRoots: ["src"], tokenFiles: [] },
    validation: { scoreFloor: 80, requiredRenders: [{ id: "desktop-loaded", state: "loaded", viewport: { width: 1440, height: 1000 } }], temporal: { required: false, scenarios: [] }, humanAcceptance: false },
  }, null, 2)}\n`);
}

test("a registry project with the same ledger writes no file and no kind, and its bundle does not name the file", () => {
  const root = mkdtempSync(join(tmpdir(), "ss-system-css-registry-"));
  try {
    writeRegistry(root, LEDGERS.both);
    const run = spawnSync(process.execPath, [resolver, "--project-root", root, "--all"], { encoding: "utf8" });
    assert.equal(run.status, 0, run.stderr);
    assert.equal(existsSync(join(root, ".styleseed/system.css")), false, "no file");
    assert.ok(!kinds(root, ".styleseed/manifests/app-settings.json").includes("system-css"), "no kind");
    const bundle = read(root, ".styleseed/bundles/app-settings.md");
    assert.ok(!bundle.includes("system.css"), "the registry bundle does not name the file");
    assert.ok(tail(bundle).endsWith(`): ${FIELD.statement}\n\n`), "the section ends with its last entry, as before");
  } finally { rmSync(root, { recursive: true, force: true }); }
});

test("renderRulesSection: the paragraph only with the lock-mode option, and only when an entry applies", () => {
  const selection = { grammar: "operations-console", adapter: "product-ui", domain: "saas", page: "settings" };
  const ledger = normalizeDecisions(structuredClone(LEDGERS.both), catalog);
  const plain = renderRulesSection(catalog.rules, selection, { decisions: ledger });
  assert.ok(!plain.includes("system.css"), "without the option: no paragraph");
  assert.ok(plain.includes(`): ${FIELD.statement}\n\n## Invariants`));
  const lock = renderRulesSection(catalog.rules, selection, { decisions: ledger, ledgerPath: ".styleseed/decisions.json", systemCss: true });
  assert.ok(lock.includes(`): ${FIELD.statement}\n\n${PARAGRAPH.both}\n\n## Invariants`), lock);
  assert.equal(lock.replace(`${PARAGRAPH.both}\n\n`, ""), renderRulesSection(catalog.rules, selection, { decisions: ledger, ledgerPath: ".styleseed/decisions.json" }), "the paragraph is the only difference");
  assert.equal(renderRulesSection(catalog.rules, selection, { decisions: [], systemCss: true }), renderRulesSection(catalog.rules, selection), "no entry: no section and no paragraph");
});
